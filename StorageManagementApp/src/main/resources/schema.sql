-- アイテム
-- * RestoreFromTempTable
CREATE TABLE IF NOT EXISTS ITEM (
  item_id INT GENERATED BY DEFAULT AS IDENTITY,
  name VARCHAR(50),
  p_item_id INT NOT NULL,
  c_no INT NOT NULL,
  category VARCHAR(50),
  number INT,
  picture_id VARCHAR(10),
  note VARCHAR(400),
  tag1 VARCHAR(50),
  tag2 VARCHAR(50),
  tag3 VARCHAR(50),
  CONSTRAINT ITEM_PKC PRIMARY KEY (ITEM_ID)
);

-- 階層情報
-- * RestoreFromTempTable
CREATE TABLE IF NOT EXISTS LAYER (
    layer_id1 INT NOT NULL,
    layer_id2 INT NOT NULL,
    layer_id3 INT NOT NULL,
    layer_id4 INT NOT NULL,
    layer_id5 INT NOT NULL,
    item_id INT NOT NULL,

    CONSTRAINT LAYER_PKC PRIMARY KEY (ITEM_ID),

    CONSTRAINT LAYER_ITEM_FK
        FOREIGN KEY (ITEM_ID)
        REFERENCES ITEM (ITEM_ID)
        ON DELETE CASCADE
);


